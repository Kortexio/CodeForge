#!/usr/bin/env node
/**
 * Copy the calibrate suite into the extension package so Settings can run
 * calibrate without a source checkout of benchmarks/.
 *
 * Target: extensions/codeforge/resources/calibrate-bench/
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'benchmarks');
const DEST = path.join(ROOT, 'extensions', 'codeforge', 'resources', 'calibrate-bench');

const TASKS = [
	'T2-feature-coupon',
	'T4-refactor-rename',
	'CS2-feature-coupon',
	'CS3-nav-vip-rate',
];
const FIXTURES = ['shop', 'billing'];
const ROOT_FILES = ['bench.mjs', 'headlessAgent.mjs', 'layout.mjs'];

function rmrf(dir) {
	fs.rmSync(dir, { recursive: true, force: true });
}

function copyFile(src, dest) {
	fs.mkdirSync(path.dirname(dest), { recursive: true });
	fs.copyFileSync(src, dest);
}

function copyDir(src, dest) {
	fs.mkdirSync(dest, { recursive: true });
	for (const ent of fs.readdirSync(src, { withFileTypes: true })) {
		if (ent.name === 'bin' || ent.name === 'obj' || ent.name === 'node_modules' || ent.name === '.git') {
			continue;
		}
		const from = path.join(src, ent.name);
		const to = path.join(dest, ent.name);
		if (ent.isDirectory()) copyDir(from, to);
		else copyFile(from, to);
	}
}

rmrf(DEST);
fs.mkdirSync(DEST, { recursive: true });

for (const f of ROOT_FILES) {
	copyFile(path.join(SRC, f), path.join(DEST, f));
}

for (const name of FIXTURES) {
	copyDir(path.join(SRC, 'fixtures', name), path.join(DEST, 'fixtures', name));
}

for (const name of TASKS) {
	copyDir(path.join(SRC, 'tasks', name), path.join(DEST, 'tasks', name));
}

copyFile(
	path.join(ROOT, 'tests', 'support', 'vscodeFsMock.js'),
	path.join(DEST, 'support', 'vscodeFsMock.js')
);

fs.writeFileSync(
	path.join(DEST, '.packaged'),
	`synced ${new Date().toISOString()}\nsource=${SRC.replace(/\\/g, '/')}\n`,
	'utf8'
);

fs.writeFileSync(
	path.join(DEST, 'README.md'),
	[
		'# Packaged calibrate suite',
		'',
		'Generated by `node scripts/sync-calibrate-bench.mjs` (also via `build:extensions`).',
		'Do not edit by hand — change files under `/benchmarks` and re-sync.',
		'',
	].join('\n'),
	'utf8'
);

console.log(`Synced calibrate suite → ${DEST}`);
console.log(`  tasks: ${TASKS.join(', ')}`);
console.log(`  fixtures: ${FIXTURES.join(', ')}`);
